// Derive the bounded runtime from the full pipeline so fixtures, image identity,
// privacy-safe diagnostics and authority configuration cannot silently drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { parse, stringify } from 'yaml';
import { policy } from './select-feature-tests.mjs';
const full = parse(readFileSync('.github/workflows/full-sanity.yml', 'utf8'));
const copy = value => structuredClone(value);
const metadata = copy(full.jobs.metadata);
const build = copy(full.jobs['build-images-once']);
build.needs = ['metadata'];
const runtime = copy(full.jobs['container-integration']);
runtime.name = 'feature-runtime';
runtime['timeout-minutes'] = 30;
delete runtime.strategy;
const baseline = new Set(policy.baselineCommands);
runtime.steps = runtime.steps.flatMap(original => {
  const step = copy(original);
  const condition = step.if;
  if (condition?.includes('STRATAAI_POST_MVP_LOAD_TESTS')) return [];
  if (condition?.includes('matrix.suite')) {
    if (!condition.includes("matrix.suite == 'browser-full'") && !baseline.has(step.name)) return [];
    if (condition.startsWith('always()')) step.if = 'always()';
    else if (condition.startsWith('failure()')) step.if = 'failure()';
    else delete step.if;
  }
  if (step.name === 'Authenticated browser E2E against exact release images') {
    step.name = 'Selected feature browser acceptance against exact images';
    step.env.STRATAAI_SELECTED_BROWSER = '${{ inputs.browser }}';
    step.run = 'node scripts/ci/run-feature-browser.mjs';
  }
  if (step.name === 'Install browser test dependencies') step.run = 'npm ci --ignore-scripts\nnpx playwright install --with-deps chromium\n';
  // Keep artifact payloads and checksum wrappers intact; only suffixes change.
  for (const field of ['name','run']) if (typeof step[field] === 'string') step[field] = step[field].replaceAll('${{ matrix.suite }}','feature').replaceAll('${{ matrix.shard }}','1');
  if (step.with?.name) step.with.name = step.with.name.replaceAll('${{ matrix.suite }}','feature').replaceAll('${{ matrix.shard }}','1');
  return [step];
});
const workflow = {
  name: 'StrataAI2 feature runtime',
  on: { workflow_call: { inputs: { browser: { required: true, type: 'string' } } } },
  permissions: { contents: 'read' },
  env: full.env,
  jobs: { metadata, 'build-images-once': build, runtime },
};
const content = '# Generated by node scripts/ci/generate-feature-runtime.mjs; edit full-sanity.yml, then regenerate.\n' + stringify(workflow, { lineWidth: 0 });
const path = '.github/workflows/feature-runtime.yml';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== content) throw new Error('Feature runtime drift: regenerate from full sanity');
} else writeFileSync(path, content);
